/* ============================================================================
   screens/kpi.js — полоса KPI. Неймспейс: PXSCREEN.kpi

   Полоса стоит НАД вкладками и видна на любой из них: это состояние среза,
   а не содержимое одного экрана. Вкладка отвечает на вопрос «как менялось»,
   полоса — на вопрос «что сейчас», и второй вопрос не должен исчезать,
   когда пользователь ушёл смотреть здоровье или трансформер.

   Отсюда же следует, что полоса НЕ ЗАВИСИТ ОТ РЕЖИМА «люди / аллокации»:
   переключатель стоит ниже вкладок и управляет их содержимым. Обе главные
   метрики стоят в полосе рядом и всегда, а режим лишь подсвечивает ту,
   в которой считает вкладка.

   Три карточки двойные, две обычные — полоса ложится в четыре колонки
   двумя строками без пустых клеток: 1+1+2 и 2+2. Двойная ширина здесь не
   украшение, а условие читаемости: во врезку идут кольцо с подписями частей
   и полоса состояний с числами, а им нужно место. В одинарной карточке
   такая врезка уже пробовалась и не работала.

   Верификация и укомплектованность показаны бубликом. Это единственные
   метрики отчёта, где заранее известно, что принято за сто процентов:
   продукты среза и план по ставкам. Крупной цифрой стоит доля, кольцо
   показывает, из чего она сложилась, в центре кольца — само целое.
   Одна и та же величина не повторяется дважды.
   ========================================================================== */
(function(){
'use strict';
const D=window.PXDATA, G=window.PXDRAW, U=window.PXUI;

function periodName(st){
  return D.MONTHS[st.i0].label+' '+D.MONTHS[st.i0].y+' — '+D.MONTHS[st.i1].label+' '+D.MONTHS[st.i1].y;
}
/* Короткие имена состояний — только для подписей под риской: место там
   на два слова, а полное имя всегда остаётся в подсказке. */
const HSHORT={norm:'ровно 100%',over:'больше 100%',under:'30–99%',
              low:'меньше 30%',zero:'ноль'};
const HCOL={norm:G.C_GREEN,over:G.C_RED,under:G.C_FLAT,low:G.C_RED,zero:G.C_RED};

function render(st,m){
  m=m||D.model(st);
  const hc=m.head.hc, fte=m.head.fte, v=m.verify, v0=m.verifyStart;
  /* Квота открывается на ставку, а не на процент, поэтому укомплектованность
     считается в людях в обоих режимах отчёта — как и сама квота. Полоса
     стоит выше переключателя режима, и зависеть от него не может. */
  const openNow=m.quota, filled=hc.end, plan=openNow+filled;
  const fillPct=plan?filled/plan*100:0;
  const plan0=m.quotaStart+hc.begin;
  const fill0=plan0?hc.begin/plan0*100:0;
  const perHead=hc.end?fte.end/hc.end:0;
  /* Подсветка главной метрики стоит ровно тогда, когда у вкладки есть
     переключатель режима. На вкладке здоровья его нет — и подсвечивать
     нечего: там всё считается в людях. Источник правды один — сам экран. */
  const sc=window.PXSCREEN[st.tab];
  const mode=st.mode, lead=!(sc&&sc.usesMode===false);

  const hTotal=m.health.reduce((a,h)=>a+h.people,0);
  const hNorm=m.health.filter(h=>h.key==='norm')[0].people;
  const hBad=m.health.filter(h=>h.bad).reduce((a,h)=>a+h.people,0);
  const hShare=hTotal?hNorm/hTotal*100:0;
  const hItems=m.health.map(h=>({name:h.name,short:HSHORT[h.key],value:h.people,
    hint:h.hint,color:HCOL[h.key]}));

  /* Верификация: зелёный и красный здесь уместны — это ровно тот случай,
     когда у величины есть оценка. Неподтверждённая аллокация идёт в P&L
     как есть, поэтому «ждёт подтверждения» — не нейтральная категория. */
  const vDonut=G.chart('donut',{
    parts:[{name:'Подтверждено',value:v.ok,color:G.C_GREEN,
            hint:'владелец продукта подтвердил состав команды'},
           {name:'Ждут подтверждения',value:v.total-v.ok,color:G.C_RED,
            hint:'состав не подтверждён — P&L считается по неподтверждённым данным'}],
    center:{value:D.fmtInt(v.total),caption:'продуктов'}},
    {fill:true,h:132,unit:'Продуктов'});

  /* Укомплектованность: белая часть с обводкой — открытая квота, ровно как
     белая часть бара в ресурсообеспеченности. Оценка живёт в дельте,
     а не в цвете: занятая ставка не «хорошо», открытая не «плохо». */
  const fDonut=G.chart('donut',{
    parts:[{name:'Занято',value:filled,color:G.C_TOTAL,
            hint:'люди, стоящие на продуктах среза'},
           {name:'Открытые квоты',value:openNow,color:'#fff',hollow:true,stroke:G.C_QUOTA,
            hint:'позиция заведена, но не закрыта'}],
    center:{value:D.fmtInt(plan),caption:'ставок в плане'}},
    {fill:true,h:132,unit:'Ставок'});

  return '<div class="kpis n4">'+
    U.kpi({label:'Уникальные сотрудники',cls:lead&&mode==='hc'?'lead-card':'',
      info:U.info({title:'Уникальные сотрудники',
        text:'Люди, у которых в выбранном срезе есть хотя бы одна аллокация. Человек, стоящий на трёх продуктах, посчитан один раз.',
        note:'Именно по этой метрике считаются HR-показатели: текучесть и оценки привязаны к человеку, а не к проценту его занятости.'}),
      value:D.fmtInt(hc.end),
      row1:U.delta('hc',hc.delta,{vs:'к началу периода',
        tip:{title:'Изменение за период',text:'Разница между концом и началом периода: '+periodName(st)+'.'}}),
      row2:'<span class="k-sub">на начало '+D.fmtInt(hc.begin)+'</span>'})+

    U.kpi({label:'Сумма аллокаций, FTE',cls:lead&&mode==='fte'?'lead-card':'',
      info:U.info({title:'Сумма аллокаций',
        text:'Сумма процентов занятости всех людей на продуктах среза, делённая на сто. Один человек на 50% и 50% даёт 1,0 FTE.',
        note:'Метрика отвечает на вопрос «сколько ставок стоит команда», а не «сколько в ней людей».'}),
      value:D.fmtFte(fte.end),
      row1:U.delta('fte',fte.delta,{vs:'к началу периода'}),
      row2:'<span class="k-sub">на человека '+D.fmtFte(perHead)+'</span>'})+

    U.kpi({label:'Здоровье аллокаций',
      info:U.info({title:'Здоровье аллокаций',
        text:'Доля сотрудников, у которых сумма аллокаций по всем продуктам равна ровно ста процентам.',
        rows:D.HEALTH.map(h=>({label:h.hint,value:h.name,color:HCOL[h.key]})),
        note:['Считается по человеку, а не по паре: перебор ставки возникает из суммы по всем продуктам сразу.',
              'Динамика и разрезы — на вкладке «Здоровье»: одного числа мало, чтобы понять, становится лучше или хуже.']}),
      value:D.fmtPct(hShare,0),
      row1:hBad
        ? '<span class="sig-chip bad">проблемных '+D.fmtInt(hBad)+'</span>'
        : '<span class="sig-chip good">расхождений нет</span>',
      row2:'<span class="k-sub">всего в срезе '+D.fmtInt(hTotal)+'</span>',
      aside:'<div class="h-cap">Состояния ставки · <b>'+D.fmtInt(hTotal)+' человек</b></div>'+
        U.stateBar(hItems,hTotal)})+

    U.kpi({label:'Верификация аллокаций',
      info:U.info({title:'Доля верифицированных продуктов',
        text:'Владелец продукта подтвердил состав команды. За сто процентов приняты продукты среза, на которых есть хотя бы один человек: пустой продукт подтверждать нечего.',
        note:['Данные каталога идут в расчёт P&L, поэтому неподтверждённая аллокация — это неверный P&L.',
              'Какие именно продукты не подтверждены — на вкладке «Здоровье».']}),
      value:D.fmtPct(v.share,0),
      row1:U.delta('pp',v.share-v0.share,{vs:'к началу периода',rate:true,
        tip:{title:'Изменение доли',text:'Разница с началом периода в процентных пунктах.'}}),
      row2:'<span class="k-sub">на начало периода '+D.fmtPct(v0.share,0)+'</span>',
      aside:'<div class="h-cap">100% = <b>продукты среза</b></div>'+vDonut})+

    U.kpi({label:'Укомплектованность квот',
      info:U.info({title:'Укомплектованность',
        text:'Занято ÷ (занято + открытые квоты). За сто процентов принят план по продуктам среза: люди на продуктах плюс незакрытые позиции.',
        note:['Квота открывается на ставку, а не на процент, поэтому и в режиме аллокаций она считается в штатных единицах.',
              'Наймом за период закрыто '+D.fmtInt(hc.hire)+'.']}),
      value:D.fmtPct(fillPct,0),
      row1:U.delta('pp',fillPct-fill0,{vs:'к началу периода',rate:true,
        tip:{title:'Изменение укомплектованности',text:'Разница с началом периода в процентных пунктах.'}}),
      row2:'<span class="k-sub">открыто '+D.fmtInt(openNow)+' квот</span>',
      aside:'<div class="h-cap">100% = <b>план по продуктам</b></div>'+fDonut})+
  '</div>';
}

window.PXSCREEN=window.PXSCREEN||{};
window.PXSCREEN.kpi={render,periodName};
})();
