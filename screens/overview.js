function render(st){
  const m=D.model(st);
  if(!m.verify.total)return U.empty('На выбранных продуктах никого нет',
    'Снимите один из фильтров слева — например, сегмент аллокации или грейд.');
  /* Порядок блоков — это порядок вопросов. Сколько людей → из кого они
     состоят → как менялось → где именно менялось.

     Динамика стоит слева и шире: это главный сюжет экрана, и читают его
     первым. Справа колонка из двух панелей: состав команды и водопад.
     Состав сверху, потому что он разбирает то число, которым водопад
     заканчивается, и потому что читать сверху вниз «из кого состоит →
     как получилось» естественнее, чем наоборот.

     Высоту колонки задаёт динамика. Состав занимает свои пять строк,
     водопад забирает весь остаток: график умеет занять любую высоту,
     и серой пустоте под колонкой взяться неоткуда. */
  return kpis(m,st)+'<div class="stack">'+
    '<div class="grid-60-40">'+dynamics(m,st)+
      '<div class="col">'+composition(m,st)+
      U.panel({title:'Как изменилось за период'+U.info({
          title:'Как читать: водопад',
          text:'Слева численность на начало периода, справа на конец. Между ними шаги, которые превратили первое во второе: каждый начинается там, где кончился предыдущий.',
          rows:[{label:LEG_HINT.hire,value:'Найм',color:G.C_HIRE},
                {label:LEG_HINT.in,value:'Вход',color:G.C_IN},
                st.mode==='fte'?{label:LEG_HINT.gain,value:'Рост',color:G.C_UP}:null,
                st.mode==='fte'?{label:LEG_HINT.cut,value:'Снижение',color:G.C_DN}:null,
                {label:LEG_HINT.out,value:'Выход',color:G.C_OUT},
                {label:LEG_HINT.attr,value:'Отток',color:G.C_ATTR}].filter(Boolean),
          note:'Серые столбцы — состояния, цветные — движения. Шаги идут в порядке жизненного цикла: пришёл в компанию, пришёл на продукт, изменил долю, ушёл с продукта, ушёл из компании.'}),
        sub:'водопад движения',
        cls:'p-wf',bodyCls:'fill-b',
        body:waterfall(m,st)})+
      '</div>'+
    '</div>'+pivot(m,st)+'</div>';
}

